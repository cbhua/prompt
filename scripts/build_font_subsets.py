#!/usr/bin/env python3
"""Build deterministic webfonts from local originals; --check needs only stdlib."""
import argparse
import hashlib
import io
import json
import re
import sys
import unicodedata
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / 'scripts/font-sources.json'
OUTPUT = ROOT / 'assets/fonts'
CSS = ROOT / 'css/fonts.css'
MANIFEST = OUTPUT / 'manifest.json'


class PageText(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts = []

    def handle_starttag(self, tag, attrs):
        for name, value in attrs:
            if name in ('alt', 'title', 'placeholder', 'aria-label', 'value', 'content') and value:
                self.parts.append(value)

    def handle_data(self, data):
        # Inline prompt templates and JavaScript messages can contain display text.
        self.parts.append(decode_escapes(data))


def decode_escapes(text):
    return re.sub(r'(?:\\u[0-9a-fA-F]{4})+', lambda m: json.loads('"' + m[0] + '"'), text)


def is_cjk(cp):
    # Chinese glyphs and punctuation only. Latin letters never enter CJK faces.
    ranges = ((0x2E80, 0x303F), (0x3100, 0x312F), (0x31A0, 0x31BF),
              (0x31C0, 0x33FF), (0x3400, 0x4DBF), (0x4E00, 0x9FFF),
              (0xF900, 0xFAFF), (0xFE10, 0xFE1F), (0xFE30, 0xFE4F),
              (0xFF01, 0xFF60), (0x20000, 0x323AF))
    return (any(start <= cp <= end for start, end in ranges)
            and 'LATIN' not in unicodedata.name(chr(cp), ''))


def collect_characters(root=ROOT):
    parts = []
    for path in sorted(root.rglob('*.html')):
        if any(part.startswith('.') or part in ('vendor', 'node_modules', 'artifacts_template')
               for part in path.relative_to(root).parts):
            continue
        parser = PageText()
        parser.feed(path.read_text())
        parts.extend(parser.parts)
    # Include dynamic UI strings and prompt templates, including escaped Unicode.
    for folder, suffixes in (('prompt', {'.md'}), ('js', {'.js'}), ('css', {'.css'})):
        for path in sorted((root / folder).rglob('*')):
            if path.suffix in suffixes and not path.name.endswith('.min.js') and path.name != 'fonts.css':
                text = path.read_text()
                parts.append(decode_escapes(text))
    # Keep printable ASCII so new English text and form input work without rebuilding.
    return sorted({ord(c) for c in ''.join(parts) if not unicodedata.category(c).startswith('C')}
                  | set(range(0x20, 0x7F)))


def digest(data):
    return hashlib.sha256(data).hexdigest()


def ranges_css(codes):
    ranges = []
    for cp in sorted(codes):
        if ranges and cp == ranges[-1][1] + 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return ', '.join(f'U+{a:04X}' if a == b else f'U+{a:04X}-{b:04X}' for a, b in ranges)


def check():
    manifest = json.loads(MANIFEST.read_text())
    characters = collect_characters()
    if (manifest['characters'] != characters
            or manifest['config_sha256'] != digest(CONFIG.read_bytes())
            or manifest['builder_sha256'] != digest(Path(__file__).read_bytes())):
        raise ValueError('Website text or font configuration changed. Run scripts/build_font_subsets.py and commit the generated files.')
    for relative, expected in manifest['artifacts'].items():
        path = ROOT / relative
        if not path.is_file() or digest(path.read_bytes()) != expected:
            raise ValueError(f'Missing or changed generated font artifact: {relative}')
    print(f'Font subsets are current ({len(characters)} site characters).')


def build():
    from fontTools import subset
    from fontTools.ttLib import TTFont

    characters = collect_characters()
    faces = json.loads(CONFIG.read_text())['faces']
    generated = {}
    records = []
    rules = ['/* Generated by scripts/build_font_subsets.py. Do not edit. */']
    for face in faces:
        path = Path(face['path']).expanduser()
        font = TTFont(path, fontNumber=face.get('index', -1), recalcTimestamp=False)
        cmap = font.getBestCmap()
        requested = {cp for cp in characters if is_cjk(cp) == (face['group'] == 'cjk')}
        supported = requested & cmap.keys()
        allowed_missing = {int(value.removeprefix('U+'), 16) for value in face.get('allow_missing', [])}
        if face['group'] == 'cjk' and requested - supported - allowed_missing:
            missing = ranges_css(requested - supported - allowed_missing)
            raise ValueError(f'{face["id"]} is missing site characters: {missing}')
        options = subset.Options()
        options.flavor = 'woff2'
        options.recalc_timestamp = False
        options.canonical_order = True
        options.desubroutinize = True
        options.layout_features = face.get('layout_features', options.layout_features)
        # Preserve notices and license metadata in every distributed subset.
        options.name_IDs = ['*']
        options.name_languages = ['*']
        options.name_legacy = True
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=supported)
        subsetter.subset(font)
        # Layout closure can retain additional mapped glyphs (e.g. mirrored quotes).
        supported = set(font.getBestCmap())
        # Distinguish the derived subset from the installed full font.
        style_name = ('Bold' if face['weight'] == '700' else 'Regular') + (' Italic' if face['style'] == 'italic' else '')
        full_name = face['family'] + ' ' + style_name
        for name_id, value in ((1, face['family']), (4, full_name),
                               (6, full_name.replace(' ', '-')), (16, face['family'])):
            for record in font['name'].names:
                if record.nameID == name_id:
                    font['name'].setName(value, name_id, record.platformID, record.platEncID, record.langID)
        font.flavor = 'woff2'
        buffer = io.BytesIO()
        font.save(buffer)
        data = buffer.getvalue()
        font.close()
        filename = face['id'] + '.woff2'
        generated[OUTPUT / filename] = data
        rules.append(f'''@font-face {{
  font-family: "{face['family']}";
  src: url("../assets/fonts/{filename}?v={digest(data)[:12]}") format("woff2");
  font-weight: {face['weight']};
  font-style: {face['style']};
  font-display: swap;
  unicode-range: {ranges_css(supported)};
}}''')
        records.append({'id': face['id'], 'bytes': len(data), 'characters': sorted(supported),
                        'source_sha256': digest(path.read_bytes())})
        print(f'{filename}: {len(supported)} characters, {len(data) / 1024:.1f} KiB')
    rules.append('''/* Optional local original font for the IPA replacement preference. */
@font-face {
  font-family: "Site Original IPA Mincho";
  src: local("IPAmjMincho"), local("IPAexMincho"), local("IPAMincho");
  font-display: swap;
  unicode-range: ''' + ranges_css({cp for cp in characters if is_cjk(cp)}) + ''';
}
:root {
  --font-sans: "Site Lucida Grande", "Lucida Grande", "Lucida Sans Unicode", -apple-system, BlinkMacSystemFont, "Segoe UI", "PingFang SC", "Hiragino Sans GB", "Microsoft YaHei", sans-serif;
  --font-serif-zh: "Site LXGW Neo ZhiSong";
  --font-serif: "Site CMU Serif", var(--font-serif-zh), "CMU Serif", "Songti SC", serif;
  --font-mono: "Site Code Latin", "Site Code CJK", "Maple Mono", "Maple Mono NF CN", ui-monospace, SFMono-Regular, Consolas, monospace;
}
:root[data-song-font="ipa"] {
  --font-serif-zh: "Site Original IPA Mincho";
}
.font-sans, .font-hei { font-family: var(--font-sans); }
.font-serif, .font-song, .font-cmu-serif { font-family: var(--font-serif); }
pre, code, kbd, samp { font-family: var(--font-mono); }
''')
    generated[CSS] = ('\n\n'.join(rules) + '\n').encode()
    manifest = {'version': 1, 'characters': characters, 'config_sha256': digest(CONFIG.read_bytes()),
                'builder_sha256': digest(Path(__file__).read_bytes()),
                'faces': records, 'artifacts': {str(p.relative_to(ROOT)): digest(data)
                                             for p, data in generated.items()}}
    # Do not overwrite existing subsets unless every face succeeded.
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for path, data in generated.items():
        path.write_bytes(data)
    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check freshness without full fonts or FontTools')
    args = parser.parse_args()
    try:
        check() if args.check else build()
    except (OSError, ValueError, ImportError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
